/// GA4 continent name for a Cloudflare cf-ipcontinent code.
pub fn continent_from_code(code: &str) -> Option<&'static str> {
    Some(match code.to_ascii_uppercase().as_str() {
        "AF" => "Africa",
        "AN" => "Antarctica",
        "AS" => "Asia",
        "EU" => "Europe",
        "NA" | "SA" => "Americas",
        "OC" => "Oceania",
        _ => return None,
    })
}

/// (country, sub_continent, continent) for an ISO alpha-2 code.
pub fn country(code: &str) -> Option<(&'static str, &'static str, &'static str)> {
    let code = code.to_ascii_uppercase();
    COUNTRIES.binary_search_by(|(c, ..)| (*c).cmp(code.as_str())).ok().map(|i| (COUNTRIES[i].1, COUNTRIES[i].2, COUNTRIES[i].3))
}
